using RobloxAntiAfk.Core.Domain;

namespace RobloxAntiAfk.App.Presentation;

public sealed record RuleItem(string Title, string Text, bool IsWarning = false);

public sealed record RuleSection(string Title, IReadOnlyList<RuleItem> Items);

/// <summary>Правила на вкладке «Как это работает». Часть текста зависит от настроек и системы.</summary>
public static class RuleCatalog
{
    public static IReadOnlyList<RuleSection> Build(AppSettings settings, bool isMac, string translationHotkey)
    {
        var effect = Texts.Effect(settings.Action);
        return
        [
            new RuleSection("Что делает программа",
            [
                new RuleItem("Сначала нажми «Запустить»",
                    "Приложение открывается выключенным и ничего не делает, пока ты сама его не запустишь. Остановить можно в любой момент той же кнопкой."),
                new RuleItem(
                    $"{Texts.ActionSummary(settings)} раз в {Texts.Minutes(settings.IntervalMinutes)}",
                    $"{Texts.ActionDescription(settings)} Обычно Roblox кикает примерно после 20 минут без действий. Всё это меняется в настройках."),
                new RuleItem(effect.Title, effect.Text, effect.IsWarning),
                new RuleItem("Можно заниматься другими делами",
                    "Если открыто другое окно, программа на секунду переключится на Roblox, сделает действие и вернёт тебя обратно. Если ты печатаешь, она подождёт паузу, но не дольше 30 секунд."),
                new RuleItem("Пропускает действие, когда идёт игра",
                    "Если Roblox открыт и в последнюю минуту кто-то нажимал клавиши или двигал мышь, действие не нужно. Это можно выключить в настройках."),
                new RuleItem("Работает со всеми окнами Roblox",
                    "Если открыто несколько окон, действие выполняется в каждом по очереди, с паузой в секунду. Если ты играешь в одном из них, это окно пропускается, но программа всё равно ненадолго переключится на остальные. Это можно выключить в настройках."),
                new RuleItem("Не даёт компьютеру уснуть",
                    "Экран и компьютер не засыпают, пока приложение запущено. Это можно выключить в настройках, но во сне Roblox отключится."),
            ]),
            new RuleSection("Что нужно для работы", isMac
                ?
                [
                    new RuleItem("Разрешение «Универсальный доступ»",
                        "Системные настройки → Конфиденциальность и безопасность → Универсальный доступ → включи Roblox AntiAFK. Без него macOS не даст кликать и нажимать клавиши. Если там уже включено, а приложение всё равно просит разрешение, удали его кнопкой «−» и добавь снова."),
                    RobloxRunning,
                    new RuleItem("Окно Roblox не свёрнуто",
                        "Свёрнутое окно приложение не разворачивает, а просто пропустит действие и напишет об этом. Оставь окно открытым, пусть даже за другими окнами."),
                    ScreenUnlocked,
                    AppOpen,
                ]
                :
                [
                    RobloxRunning,
                    new RuleItem("Свёрнутое окно не помеха",
                        "Если Roblox свёрнут, приложение развернёт его на секунду, сделает действие и свернёт обратно."),
                    ScreenUnlocked,
                    AppOpen,
                ]),
            new RuleSection("Что важно знать",
            [
                new RuleItem("Некоторые игры кикают сами",
                    "У игры может быть свой таймер, который следит за движением персонажа. От такого кика клик на месте не спасёт. Может помочь режим «Шаг W → S» из настроек, но это не гарантия.", IsWarning: true),
                new RuleItem("Правила конкретной игры",
                    "Где-то стоять без дела запрещено правилами самой игры. Перед долгим AFK загляни в них.", IsWarning: true),
                new RuleItem("Если Roblox отключился",
                    settings.ReconnectEnabled
                        ? "Программа увидит запись об отключении в журнале Roblox и зайдёт по твоей ссылке, максимум 5 попыток подряд. Если закрыть окно самой, она обратно не зайдёт."
                        : "Сама программа в игру обратно не зайдёт, пока не включишь переподключение в настройках."),
                new RuleItem("Как проверить",
                    "Нажми «Запустить», а затем «Сделать сейчас»: в списке слева появится запись с зелёной точкой. Затем оставь Roblox примерно на 25 минут. Если не кикнуло, всё работает."),
            ]),
            new RuleSection("Перевод текста из игры", BuildTranslationRules(isMac, translationHotkey)),
        ];
    }

    private static IReadOnlyList<RuleItem> BuildTranslationRules(bool isMac, string hotkey)
    {
        List<RuleItem> rules =
        [
            new RuleItem("Как это работает",
                "Приложение делает снимок выбранной части экрана, распознаёт на нём текст и показывает русский перевод. В Roblox ничего не внедряется и не меняется: это обычное чтение картинки с экрана. По умолчанию перевод выключен, включается на вкладке «Перевод»."),
            new RuleItem($"{hotkey}, обвести текст, и готов перевод",
                $"Нажми {hotkey}, и картинка в окне Roblox замрёт, как при скриншоте. Зажми левую кнопку мыши и обведи текст: прочитается именно застывший кадр, поэтому движущийся текст не убежит. Этот клик в игру не попадёт. Сама игра при этом идёт дальше, и клавиши до неё доходят. Перевод появится под выделением, а если там нет места, то над ним. Клики проходят сквозь подпись, поэтому она не мешает играть. Следующее нажатие спрячет перевод, и всё можно повторить с другим текстом. Пока приложение ждёт выделения, ещё одно нажатие отменит его. Пока перевод включён, это сочетание не работает в других программах. Раскладка не важна."),
            new RuleItem("Можно запомнить одно место",
                $"Если текст всегда появляется в одном месте, выключи «Выделять каждый раз» и выбери область один раз. Тогда {hotkey} сразу покажет перевод этого места. Область будет двигаться вместе с окном."),
            new RuleItem("Перевод может обновляться сам",
                "Если включить «Обновлять самому», пока перевод показан, область читается раз в 2 секунды. Текст исчез, и подпись прячется. Появился новый, и она показывается снова."),
            new RuleItem("Что уходит в интернет",
                "Распознавание работает на компьютере, снимки никуда не отправляются и не сохраняются. В сервис перевода уходит только распознанный текст, но если в области окажется чат или ник, они уйдут тоже. Экран читается, только пока Roblox на переднем плане, поэтому текст из других окон туда не попадёт.", IsWarning: true),
            new RuleItem("Что читается плохо",
                "Обычный текст диалогов и меню распознаётся хорошо. Декоративные шрифты, надписи на 3D-объектах и текст на пёстром фоне могут читаться с ошибками, а за быстро движущимся текстом перевод не успеет.", IsWarning: true),
            new RuleItem("Если нет интернета",
                "Вместо перевода подпись покажет исходный английский текст и напомнит проверить интернет."),
            new RuleItem("Если подпись не видно",
                isMac
                    ? "Переключи Roblox из полноэкранного режима в окно. На весь экран подпись показывается поверх игры, но значок приложения на это время пропадает из Dock: иначе macOS её не покажет."
                    : "Переключи Roblox из полноэкранного режима в окно. В некоторых режимах Windows не показывает другие окна поверх игры и не отдаёт её изображение."),
        ];

        if (isMac)
        {
            rules.Insert(1, new RuleItem("Разрешение «Запись экрана»",
                "Без него macOS не даст прочитать экран. Системные настройки → Конфиденциальность и безопасность → Запись экрана → включи Roblox AntiAFK и открой приложение заново."));
        }

        return rules;
    }

    private static RuleItem RobloxRunning => new("Запущенный Roblox",
        "Приложение можно открыть раньше игры, оно само найдёт окно Roblox.");

    private static RuleItem ScreenUnlocked => new("Экран не заблокирован",
        "На заблокированном экране программа ничего не сможет нажать. Если закрыть крышку ноутбука, он может уснуть, и Roblox отключится.");

    private static RuleItem AppOpen => new("Приложение открыто",
        "Закроешь окно, и всё остановится, если в настройках не включено «Прятать в трей». Настройки сохраняются, но при следующем открытии приложение снова будет выключено, если не включён запуск сразу.");
}
