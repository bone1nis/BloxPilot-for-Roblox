using RobloxAntiAfk.Core.Domain;
using RobloxAntiAfk.Core.Localization;

namespace RobloxAntiAfk.App.Presentation;

public sealed record RuleItem(string Title, string Text, bool IsWarning = false);

public sealed record RuleSection(string Title, IReadOnlyList<RuleItem> Items);

/// <summary>Правила на вкладке «Как это работает». Часть текста зависит от настроек и системы.</summary>
public static class RuleCatalog
{
    public static IReadOnlyList<RuleSection> Build(AppSettings settings, bool isMac, string translationHotkey)
    {
        var effect = Texts.Effect(settings.Action);
        return
        [
            new RuleSection(L.T("Что делает программа"),
            [
                new RuleItem(L.T("Сначала нажми «Запустить»"),
                    L.T("Приложение открывается выключенным и ничего не делает, пока ты сама его не запустишь. Остановить можно в любой момент той же кнопкой.")),
                new RuleItem(
                    L.F("{0} раз в {1}", Texts.ActionSummary(settings), Texts.Minutes(settings.IntervalMinutes)),
                    L.F("{0} Обычно Roblox кикает примерно после 20 минут без действий. Всё это меняется в настройках.", Texts.ActionDescription(settings))),
                new RuleItem(effect.Title, effect.Text, effect.IsWarning),
                new RuleItem(L.T("Можно заниматься другими делами"),
                    L.T("Если открыто другое окно, программа на секунду переключится на Roblox, сделает действие и вернёт тебя обратно. Если ты печатаешь, она подождёт паузу, но не дольше 30 секунд.")),
                new RuleItem(L.T("Пропускает действие, когда идёт игра"),
                    L.T("Если Roblox открыт и в последнюю минуту кто-то нажимал клавиши или двигал мышь, действие не нужно. Это можно выключить в настройках.")),
                new RuleItem(L.T("Работает со всеми окнами Roblox"),
                    L.T("Если открыто несколько окон, действие выполняется в каждом по очереди, с паузой в секунду. Если ты играешь в одном из них, это окно пропускается, но программа всё равно ненадолго переключится на остальные. Это можно выключить в настройках.")),
                new RuleItem(L.T("Не даёт компьютеру уснуть"),
                    L.T("Экран и компьютер не засыпают, пока приложение запущено. Это можно выключить в настройках, но во сне Roblox отключится.")),
            ]),
            new RuleSection(L.T("Что нужно для работы"), isMac
                ?
                [
                    new RuleItem(L.T("Разрешение «Универсальный доступ»"),
                        L.T("Системные настройки → Конфиденциальность и безопасность → Универсальный доступ → включи BloxPilot. Без него macOS не даст кликать и нажимать клавиши. Если там уже включено, а приложение всё равно просит разрешение, удали его кнопкой «−» и добавь снова.")),
                    RobloxRunning,
                    new RuleItem(L.T("Окно Roblox не свёрнуто"),
                        L.T("Свёрнутое окно приложение не разворачивает, а просто пропустит действие и напишет об этом. Оставь окно открытым, пусть даже за другими окнами.")),
                    ScreenUnlocked,
                    AppOpen,
                ]
                :
                [
                    RobloxRunning,
                    new RuleItem(L.T("Свёрнутое окно не помеха"),
                        L.T("Если Roblox свёрнут, приложение развернёт его на секунду, сделает действие и свернёт обратно.")),
                    ScreenUnlocked,
                    AppOpen,
                ]),
            new RuleSection(L.T("Что важно знать"),
            [
                new RuleItem(L.T("Некоторые игры кикают сами"),
                    L.T("У игры может быть свой таймер, который следит за движением персонажа. От такого кика клик на месте не спасёт. Может помочь режим «Шаг W → S» из настроек, но это не гарантия."), IsWarning: true),
                new RuleItem(L.T("Правила конкретной игры"),
                    L.T("Где-то стоять без дела запрещено правилами самой игры. Перед долгим AFK загляни в них."), IsWarning: true),
                new RuleItem(L.T("Если Roblox отключился"),
                    settings.ReconnectEnabled
                        ? L.T("Программа увидит запись об отключении в журнале Roblox и зайдёт по твоей ссылке, максимум 5 попыток подряд. Если закрыть окно самой, она обратно не зайдёт.")
                        : L.T("Сама программа в игру обратно не зайдёт, пока не включишь переподключение в настройках.")),
                new RuleItem(L.T("Как проверить"),
                    L.T("Нажми «Запустить», а затем «Сделать сейчас»: в списке слева появится запись с зелёной точкой. Затем оставь Roblox примерно на 25 минут. Если не кикнуло, всё работает.")),
            ]),
            new RuleSection(L.T("Уведомления в Telegram"),
            [
                new RuleItem(L.T("Как подключить"),
                    L.T("Создай бота через @BotFather, напиши ему любое сообщение, вставь токен в настройках и нажми «Подключить». Придёт проверочное сообщение. Бот сообщит об отключении от сервера, пока приложение открыто, даже если оно не запущено кнопкой.")),
                new RuleItem(L.T("Если нет интернета"),
                    L.T("Сообщение ждёт до 6 часов и уйдёт, когда связь появится. Если закрыть приложение раньше, неотправленные сообщения пропадут.")),
                new RuleItem(L.T("Если Telegram работает только с VPN"),
                    L.T("Без VPN бот не сможет отправить сообщение, но поможет бесплатный посредник на Cloudflare. Создай его один раз: зарегистрируйся на cloudflare.com, открой Workers & Pages, создай Worker на основе Hello World и нажми Deploy. Затем нажми Edit code, замени весь код на код из файла packaging/telegram-relay/worker.js в репозитории bone1nis/BloxPilot-for-Roblox на GitHub и снова нажми Deploy.")),
                new RuleItem(L.T("Как подключить посредника"),
                    L.T("Скопируй адрес вида https://имя.твой-аккаунт.workers.dev. Выключи VPN и открой его в браузере: должно появиться «Посредник работает». Новый адрес может заработать не сразу, поэтому при ошибке безопасного подключения подожди пару минут и перезапусти браузер. Затем вставь адрес в поле посредника в настройках и нажми «Подключить».")),
                new RuleItem(L.T("Что важно про посредника"),
                    L.T("Токен бота проходит через посредника, поэтому указывай только своего. Если он указан, сообщения идут только через него. Если он перестал отвечать, очисти поле и включи VPN."), IsWarning: true),
            ]),
            new RuleSection(L.T("Перевод текста из игры"), BuildTranslationRules(isMac, translationHotkey)),
        ];
    }

    private static IReadOnlyList<RuleItem> BuildTranslationRules(bool isMac, string hotkey)
    {
        List<RuleItem> rules =
        [
            new RuleItem(L.T("Как это работает"),
                L.T("Приложение делает снимок выбранной части экрана, распознаёт на нём текст и показывает русский перевод. В Roblox ничего не внедряется и не меняется: это обычное чтение картинки с экрана. По умолчанию перевод выключен, включается на вкладке «Перевод».")),
            new RuleItem(L.F("{0}, обвести текст, и готов перевод", hotkey),
                L.F("Нажми {0}, и картинка в окне Roblox замрёт, как при скриншоте. Зажми левую кнопку мыши и обведи текст: прочитается именно застывший кадр, поэтому движущийся текст не убежит. Этот клик в игру не попадёт. Сама игра при этом идёт дальше, и клавиши до неё доходят, кроме Esc. Перевод появится под выделением, а если там нет места, то над ним. Чтобы убрать перевод, кликни левой или правой кнопкой в любом месте окна Roblox или снова нажми сочетание. Этот клик в игру не попадёт, а клавиши работают как обычно. Потом всё можно повторить с другим текстом. Пока приложение ждёт выделения, его отменит Esc, правая кнопка мыши или ещё одно нажатие сочетания. Пока перевод включён, это сочетание не работает в других программах. Раскладка не важна.", hotkey)),
            new RuleItem(L.T("Сочетание можно поменять"),
                L.T("На вкладке «Перевод» и в настройках можно поставить своё сочетание или одну клавишу. Одиночная клавиша не будет работать в игре и других программах, пока сочетание занято приложением. Esc без других клавиш поставить нельзя: он отменяет выделение.")),
            new RuleItem(L.T("Можно запомнить одно место"),
                L.F("Если текст всегда появляется в одном месте, выключи «Выделять каждый раз» и выбери область один раз. Тогда {0} сразу покажет перевод этого места. Область будет двигаться вместе с окном.", hotkey)),
            new RuleItem(L.T("Перевод может обновляться сам"),
                L.T("Если включить «Обновлять самому», пока перевод показан, область читается раз в 2 секунды. Текст исчез, и подпись прячется. Появился новый, и она показывается снова.")),
            new RuleItem(L.T("Что уходит в интернет"),
                L.T("Распознавание работает на компьютере, снимки никуда не отправляются и не сохраняются. В сервис перевода уходит только распознанный текст, но если в области окажется чат или ник, они уйдут тоже. Экран читается, только пока Roblox на переднем плане, поэтому текст из других окон туда не попадёт."), IsWarning: true),
            new RuleItem(L.T("Что читается плохо"),
                L.T("Обычный текст диалогов и меню распознаётся хорошо. Декоративные шрифты, надписи на 3D-объектах и текст на пёстром фоне могут читаться с ошибками, а за быстро движущимся текстом перевод не успеет."), IsWarning: true),
            new RuleItem(L.T("Если нет интернета"),
                L.T("Вместо перевода подпись покажет исходный английский текст и напомнит проверить интернет.")),
            new RuleItem(L.T("Если подпись не видно"),
                isMac
                    ? L.T("Переключи Roblox из полноэкранного режима в окно. На весь экран подпись показывается поверх игры, но значок приложения на это время пропадает из Dock: иначе macOS её не покажет.")
                    : L.T("Переключи Roblox из полноэкранного режима в окно. В некоторых режимах Windows не показывает другие окна поверх игры и не отдаёт её изображение.")),
        ];

        if (isMac)
        {
            rules.Insert(1, new RuleItem(L.T("Разрешение «Запись экрана»"),
                L.T("Без него macOS не даст прочитать экран. Системные настройки → Конфиденциальность и безопасность → Запись экрана → включи BloxPilot и открой приложение заново.")));
        }

        return rules;
    }

    private static RuleItem RobloxRunning => new(L.T("Запущенный Roblox"),
        L.T("Приложение можно открыть раньше игры, оно само найдёт окно Roblox."));

    private static RuleItem ScreenUnlocked => new(L.T("Экран не заблокирован"),
        L.T("На заблокированном экране программа ничего не сможет нажать. Если закрыть крышку ноутбука, он может уснуть, и Roblox отключится."));

    private static RuleItem AppOpen => new(L.T("Приложение открыто"),
        L.T("Закроешь окно, и всё остановится, если в настройках не включено «Прятать в трей». Настройки сохраняются, но при следующем открытии приложение снова будет выключено, если не включён запуск сразу."));
}
