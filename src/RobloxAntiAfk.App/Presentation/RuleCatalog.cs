using RobloxAntiAfk.Core.Domain;

namespace RobloxAntiAfk.App.Presentation;

public sealed record RuleItem(string Title, string Text, bool IsWarning = false);

public sealed record RuleSection(string Title, IReadOnlyList<RuleItem> Items);

/// <summary>Правила на вкладке «Как это работает». Часть текста зависит от настроек и системы.</summary>
public static class RuleCatalog
{
    public static IReadOnlyList<RuleSection> Build(AppSettings settings, bool isMac)
    {
        var effect = Texts.Effect(settings.Action);
        return
        [
            new RuleSection("Что делает программа",
            [
                new RuleItem(
                    $"{Texts.ActionSummary(settings)} раз в {Texts.Minutes(settings.IntervalMinutes)}",
                    $"{Texts.ActionDescription(settings)} Обычно Roblox кикает примерно после 20 минут без действий. Всё это меняется в настройках."),
                new RuleItem(effect.Title, effect.Text, effect.IsWarning),
                new RuleItem("Можно заниматься другими делами",
                    "Если открыто другое окно, программа на секунду переключится на Roblox, сделает действие и вернёт тебя обратно. Если ты печатаешь, она подождёт паузу, но не дольше 30 секунд."),
                new RuleItem("Пропускает действие, когда идёт игра",
                    "Если Roblox открыт и в последнюю минуту кто-то нажимал клавиши или двигал мышь, действие не нужно. Это можно выключить в настройках."),
                new RuleItem("Работает со всеми окнами Roblox",
                    "Если открыто несколько окон, действие выполняется в каждом по очереди, с паузой в секунду. Если ты играешь в одном из них, это окно пропускается, но программа всё равно ненадолго переключится на остальные. Это можно выключить в настройках."),
                new RuleItem("Не даёт компьютеру уснуть",
                    "Экран и компьютер не засыпают, пока приложение открыто и не на паузе. Это можно выключить в настройках, но во сне Roblox отключится."),
            ]),
            new RuleSection("Что нужно для работы", isMac
                ?
                [
                    new RuleItem("Разрешение «Универсальный доступ»",
                        "Системные настройки → Конфиденциальность и безопасность → Универсальный доступ → включи Roblox AntiAFK. Без него macOS не даст кликать и нажимать клавиши. Если там уже включено, а приложение всё равно просит разрешение, удали его кнопкой «−» и добавь снова."),
                    RobloxRunning,
                    new RuleItem("Окно Roblox не свёрнуто",
                        "Свёрнутое окно приложение не разворачивает, а просто пропустит действие и напишет об этом. Оставь окно открытым, пусть даже за другими окнами."),
                    ScreenUnlocked,
                    AppOpen,
                ]
                :
                [
                    RobloxRunning,
                    new RuleItem("Свёрнутое окно не помеха",
                        "Если Roblox свёрнут, приложение развернёт его на секунду, сделает действие и свернёт обратно."),
                    ScreenUnlocked,
                    AppOpen,
                ]),
            new RuleSection("Что важно знать",
            [
                new RuleItem("Некоторые игры кикают сами",
                    "У игры может быть свой таймер, который следит за движением персонажа. От такого кика клик на месте не спасёт. Может помочь режим «Шаг W → S» из настроек, но это не гарантия.", IsWarning: true),
                new RuleItem("Правила конкретной игры",
                    "Где-то стоять без дела запрещено правилами самой игры. Перед долгим AFK загляни в них.", IsWarning: true),
                new RuleItem("Отключения из-за интернета",
                    "Если Roblox отключился из-за сети или перезапуска сервера, программа не зайдёт обратно сама."),
                new RuleItem("Как проверить",
                    "Нажми «Сделать сейчас»: в списке слева появится запись с зелёной точкой. Затем оставь Roblox примерно на 25 минут. Если не кикнуло, всё работает."),
            ]),
        ];
    }

    private static RuleItem RobloxRunning => new("Запущенный Roblox",
        "Приложение можно открыть раньше игры, оно само найдёт окно Roblox.");

    private static RuleItem ScreenUnlocked => new("Экран не заблокирован",
        "На заблокированном экране программа ничего не сможет нажать. Если закрыть крышку ноутбука, он может уснуть, и Roblox отключится.");

    private static RuleItem AppOpen => new("Приложение открыто",
        "Закроешь окно, и всё остановится. Сворачивать его можно. Настройки сохраняются.");
}
